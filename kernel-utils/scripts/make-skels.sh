#!/usr/bin/env bash
# Generate lab skeletons from templates/ into labs/ without touching existing files.
# Only the lab's top-level Kbuild, which lists the tasks, is always regenerated.
source "$(dirname -- "${BASH_SOURCE[0]}")/common.sh"
require_linux
need python3 find sort
(( $# == 0 )) || die 'Usage: make skels LAB=lab-name[/task] [TODO=0]'
[[ ${LAB:-} =~ ^[A-Za-z0-9_.-]+(/[A-Za-z0-9_.-]+)*$ ]] || die 'Set LAB to a directory inside templates/, e.g. LAB=lab02-kernel-api.'
todo=${TODO:-0}
[[ $todo =~ ^[0-9]+$ ]] || die 'TODO must be a non-negative integer.'
tpl_base=$(realpath -e -- "$STUDY_ROOT/templates")
src=$(realpath -e -- "$tpl_base/$LAB" 2>/dev/null) || die "No template directory: templates/$LAB"
[[ -d $src && $src == "$tpl_base"/* ]] || die 'LAB must stay inside templates/.'
rel=${src#"$tpl_base"/}
lab_base="$STUDY_ROOT/labs"
[[ ! -L $lab_base ]] || die 'Refusing to write through a symlinked labs/.'
mkdir -p "$CACHE_DIR"
tmp=$(mktemp -d "$CACHE_DIR/skels.XXXXXX")
cleanup() { [[ $tmp == "$CACHE_DIR"/skels.* && -d $tmp ]] && rm -rf -- "$tmp"; }
trap cleanup EXIT

# Build artifacts from checking a template in place are not lab sources.
(cd "$tpl_base" && find "$rel" -type f ! -name '.*' ! -name '*.o' ! -name '*.ko' ! -name '*.mod' \
    ! -name '*.mod.c' ! -name Module.symvers ! -name modules.order -print0 | sort -z \
    | xargs -0 python3 -I -B "$STUDY_ROOT/scripts/generate_skels.py" --output "$tmp" --todo "$todo") >/dev/null

created=0 kept=0
while IFS= read -r -d '' file; do
    path=${file#"$tmp"/}
    dest=$(realpath -m -- "$lab_base/$path")
    [[ $dest == "$lab_base"/* ]] || die "Refusing to write outside labs/: $path"
    if [[ -e $dest || -L $dest ]]; then
        log "Kept existing labs/$path"
        kept=$((kept + 1))
        continue
    fi
    mkdir -p -- "$(dirname -- "$dest")"
    cp -- "$file" "$dest"
    created=$((created + 1))
done < <(find "$tmp" -type f -print0 | sort -z)

log "Skeletons for $rel: $created created, $kept kept in labs/$rel."
(( kept == 0 )) || log 'Existing files are never overwritten. Move a file away to regenerate it.'

# Like upstream skels/Kbuild: one kbuild run builds every task, so modpost sees
# symbols exported by one task module when linking another.
lab_name=${rel%%/*}
lab_dir="$lab_base/$lab_name"
top="$lab_dir/Kbuild"
if [[ ! -f $tpl_base/$lab_name/Kbuild ]]; then
    [[ ! -L $top ]] || die "Refusing to write through a symlink: labs/$lab_name/Kbuild"
    {
        echo '# Generated by make skels; do not edit. Lists every task of this lab.'
        while IFS= read -r -d '' kbuild; do
            task=${kbuild%/Kbuild}
            echo "obj-m += ${task##*/}/"
        done < <(find "$lab_dir" -mindepth 2 -maxdepth 2 -name Kbuild -print0 | sort -z)
    } > "$tmp/Kbuild.top"
    mv -- "$tmp/Kbuild.top" "$top"
fi
log "Next: make lab LAB=$lab_name"
